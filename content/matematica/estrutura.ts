export const matSectionById = (id: string): Section | undefined => MAT_SECTIONS.find(s => s.id === id);
export function matSectionInfo(id: string) {
  const section = matSectionById(id);
  const active = Object.values(MAT_TEMPLATE_SECTION).filter(s => s === id).length;
  const lesson = !!section?.lessonId;
  const status = availability(active, lesson);
  return { active, total: active, lesson, status, functional: status !== 'preparacao' };
}
