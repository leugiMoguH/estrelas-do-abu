import {test,expect} from '@playwright/test';
import {defaultSave} from '../../src/core/save';
import {defaultAvatar} from '../../src/art/catalog';
test('B: reservas fora da loja; compra unica, inventario e conjunto integral persistem',async({page},info)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 const avatar={...defaultAvatar(),top:'m-vestido',bottom:'bottom-calcoes',abuBody:'b-abu-colete',brows:'arqueadas',faceShape:'sardas'};
 await page.addInitScript(({avatar,save})=>{if(!localStorage.getItem('eda:app:v1')){localStorage.setItem('eda:app:v1',JSON.stringify({profile:{version:1,onboarded:true,avatar},favorites:[avatar]}));localStorage.setItem('eda:save:v2',JSON.stringify(save));}}, {avatar,save:{...defaultSave(),stars:100,ownedItems:['m-vestido','b-abu-colete','bottom-calcoes']}});
 const open=async()=>{await page.getByRole('button',{name:/Continuar/}).first().click();await page.getByRole('button',{name:/^Loja$/}).first().click();};
 await page.goto('/?tema=d');await open();
 await expect(page.locator('.extras-item').filter({hasText:'Vestido de pregas com gola'})).toHaveCount(0);
 await expect(page.locator('.extras-item').filter({hasText:'Colete acolchoado do Abu'})).toHaveCount(0);
 const card=page.locator('.extras-item').filter({has:page.getByRole('heading',{name:'Casaco curto de malha',exact:true})});
 await card.getByRole('button',{name:'Comprar e equipar'}).click();
 await expect(card.getByRole('button',{name:'Equipado',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'Coleção',exact:true}).click();
 await expect(page.locator('.extras-item').filter({hasText:'Vestido de pregas com gola'})).toContainText('Coleção mensal');
 await expect(page.locator('.extras-item').filter({hasText:'Colete acolchoado do Abu'})).toContainText('Prémio de teste');
 const bottomCard=page.locator('.extras-item').filter({has:page.getByRole('heading',{name:'Calções',exact:true})});
 await expect(bottomCard.locator('[data-layer="bottom"]')).toBeVisible();
 await expect(bottomCard.getByRole('button',{name:'Guardado sob conjunto'})).toBeDisabled();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:info.outputPath('block-b-inventory.png'),fullPage:true,animations:'disabled'});
 await page.reload();await open();
 const saved=await page.evaluate(()=>({app:JSON.parse(localStorage.getItem('eda:app:v1')!),save:JSON.parse(localStorage.getItem('eda:save:v2')!)}));
 expect(saved.save.stars).toBe(86);expect(saved.save.ownedItems.filter((id:string)=>id==='b-casaco')).toHaveLength(1);
 expect(saved.app.profile.avatar).toMatchObject({...avatar,outer:'b-casaco'});
 await expect(page.locator('.extras-preview [data-layer="bottom"]')).toHaveCount(0);
 await expect(page.locator('.abu-preview [data-item="b-abu-colete"]')).toBeVisible();
 expect(errors).toEqual([]);
});
